"""Generate `templates/_fonts.html` — the shared @font-face partial used by every
card template so the rendered PNGs wear the same editorial type as the studio
(Fraunces display + Newsreader serif). Fonts are base64-embedded (not CDN/file
paths) because Playwright renders via `set_content` with an about:blank base URL,
so inlined data URIs are the only deterministic way to guarantee the glyphs are
present at render time. Re-run this only when the font set changes.

    python backend/app/rendering/assets/build_fonts_partial.py
"""

from __future__ import annotations

import base64
import re
import urllib.request
from pathlib import Path

# Browser UA forces the CSS2 API to serve woff2 (its best-compressed format).
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0 Safari/537.36"
)

# family, css-weight, style, our @font-face weight/style — only the cuts the
# templates actually use, to keep the embedded payload lean.
FACES = [
    ("Newsreader", "Newsreader:ital,wght@0,400", "normal", 400),
    ("Newsreader", "Newsreader:ital,wght@1,400", "italic", 400),
    ("Fraunces", "Fraunces:ital,opsz,wght@0,9..144,500", "normal", 500),
    ("Fraunces", "Fraunces:ital,opsz,wght@0,9..144,600", "normal", 600),
]

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "templates" / "_fonts.html"


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def latin_woff2_url(css: str) -> str:
    """Pick the @font-face block whose unicode-range covers basic latin."""
    blocks = re.findall(r"@font-face\s*{[^}]*}", css)
    for b in blocks:
        # The 'latin' subset block includes U+0000-00FF; prefer it.
        if "U+0000" in b or "/* latin */" in css.split(b)[0][-40:]:
            m = re.search(r"url\((https://[^)]+\.woff2)\)", b)
            if m:
                return m.group(1)
    # Fallback: first woff2 anywhere.
    m = re.search(r"url\((https://[^)]+\.woff2)\)", css)
    if not m:
        raise RuntimeError("no woff2 url found in CSS")
    return m.group(1)


def main() -> None:
    faces_css: list[str] = []
    for family, spec, style, weight in FACES:
        css_url = f"https://fonts.googleapis.com/css2?family={spec}&display=swap"
        css = fetch(css_url).decode("utf-8")
        woff2_url = latin_woff2_url(css)
        data = fetch(woff2_url)
        b64 = base64.b64encode(data).decode("ascii")
        faces_css.append(
            f"      @font-face {{\n"
            f"        font-family: '{family}';\n"
            f"        font-style: {style};\n"
            f"        font-weight: {weight};\n"
            f"        font-display: block;\n"
            f"        src: url(data:font/woff2;base64,{b64}) format('woff2');\n"
            f"      }}"
        )
        print(f"embedded {family} {weight} {style} ({len(data)//1024} KB)")

    body = "\n".join(faces_css)
    out = (
        "<!-- GENERATED by assets/build_fonts_partial.py — do not edit by hand.\n"
        "     Shared editorial type for every card template (Fraunces display +\n"
        "     Newsreader serif), base64-embedded so Playwright set_content renders\n"
        "     the glyphs deterministically. Included in each template's <head>. -->\n"
        "<style>\n"
        f"{body}\n"
        "      /* Editorial type classes — the artifact mirrors the studio. */\n"
        "      .display { font-family: 'Fraunces', ui-serif, Georgia, serif; "
        "font-optical-sizing: auto; }\n"
        "      .serif   { font-family: 'Newsreader', ui-serif, Georgia, serif; }\n"
        "      .sans    { font-family: ui-sans-serif, system-ui, -apple-system, "
        '"Segoe UI", sans-serif; }\n'
        "</style>\n"
    )
    OUT.write_text(out, encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size//1024} KB)")


if __name__ == "__main__":
    main()
